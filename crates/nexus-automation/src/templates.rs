//! Biblioteca de automatizaciones preconfiguradas. Cada plantilla es un
//! CreateAutomation completo y funcional que el usuario activa y personaliza.

use nexus_core::{
    AutomationFlow, AutomationLimits, AutomationMode, AutomationTemplate, CompareOp, Condition,
    CreateAutomation, FlowStep, ScheduleSpec, StepKind, Trigger, TriggerEntry,
};
use serde_json::json;

fn step(id: &str, kind: StepKind, next: Option<&str>) -> FlowStep {
    FlowStep {
        id: id.into(),
        kind,
        next: next.map(Into::into),
    }
}

fn flow(entry: &str, steps: Vec<FlowStep>) -> AutomationFlow {
    AutomationFlow {
        version: 1,
        steps,
        entry: Some(entry.into()),
        positions: Default::default(),
    }
}

fn daily(time: &str) -> Trigger {
    Trigger::Schedule {
        spec: ScheduleSpec {
            kind: "daily".into(),
            time: Some(time.into()),
            ..Default::default()
        },
    }
}

fn event(name: &str) -> Trigger {
    Trigger::Event {
        event: name.into(),
        filter: json!({}),
    }
}

fn agent(id: &str, agent_id: &str, goal: &str, next: Option<&str>) -> FlowStep {
    step(
        id,
        StepKind::Agent {
            agent_id: agent_id.into(),
            goal: goal.into(),
            approval: None,
        },
        next,
    )
}

fn notify(id: &str, title: &str, body: &str, next: Option<&str>) -> FlowStep {
    step(
        id,
        StepKind::Notification {
            title: title.into(),
            body: body.into(),
        },
        next,
    )
}

fn save_note(id: &str, title: &str, content: &str, tags: &[&str], next: Option<&str>) -> FlowStep {
    step(
        id,
        StepKind::Action {
            action: "knowledge.save_summary".into(),
            params: json!({"title": title, "content": content, "tags": tags}),
            approval: None,
        },
        next,
    )
}

fn end(id: &str) -> FlowStep {
    step(id, StepKind::End, None)
}

